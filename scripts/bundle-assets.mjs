// Packs the static export (./out) into worker/assets.gen.js so the worker can
// serve the app itself. Wrangler's separate asset upload needs a short-lived
// upload token that some networks strip; bundling avoids that step.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = "out";
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".woff2": "font/woff2",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".webmanifest": "application/manifest+json",
};
const TEXT = new Set([".html", ".js", ".css", ".txt", ".svg", ".json", ".webmanifest"]);

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
};
walk(ROOT);

const entries = files.map((p) => {
  const ext = extname(p);
  const type = TYPES[ext] ?? "application/octet-stream";
  const path = "/" + relative(ROOT, p).split("\\").join("/");
  const buf = readFileSync(p);
  return TEXT.has(ext)
    ? `${JSON.stringify(path)}:{t:${JSON.stringify(type)},s:${JSON.stringify(buf.toString("utf8"))}}`
    : `${JSON.stringify(path)}:{t:${JSON.stringify(type)},b:${JSON.stringify(buf.toString("base64"))}}`;
});

writeFileSync("worker/assets.gen.js", `// Generated by scripts/bundle-assets.mjs. Do not edit.\nexport default {${entries.join(",\n")}};\n`);
console.log(`Bundled ${files.length} files into worker/assets.gen.js`);
